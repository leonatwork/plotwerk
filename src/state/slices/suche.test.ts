import { describe, expect, it, vi } from 'vitest';
import { demoFs } from '../../../fixtures/demoProjekt';
import { erstelleStore } from '../store';
import { sucheProjekt } from '@core/suche';
import { tagSchluessel } from '@core/statistik';
import { ankerFinden, klartext, wortzahl } from '@core/text';
import { erstelleDemoBackend } from '../../backend/demo';

describe('Ersetzen mit Sicherheitsnetz', () => {
  it.each(['einzeln', 'alle'] as const)('synchronisiert Kapiteltitel beim Ersetzen (%s), sichert vorher und nimmt beide Titel gemeinsam zurück', async modus => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    const d = store.getState().daten!;
    const titel = d.plaene.flut!.titel;
    const original = await fs.lesen('manuskript/flut.md');
    const treffer = sucheProjekt(d, titel).find(t => t.feld.pfad.join('/') === 'plaene/flut/titel')!;
    expect(treffer).toBeDefined();
    const schreiben = vi.spyOn(fs, 'schreiben');
    const r = await store.getState().suche.ersetzen(titel, 'Hafenlichter', {}, modus === 'einzeln' ? {einzeln:treffer} : {erwartet:[treffer]});
    expect(r).toEqual({anzahl:1,fehler:[]});
    expect(store.getState().daten!.plaene.flut!.titel).toBe('Hafenlichter');
    expect(store.getState().daten!.kapitel.flut!.titel).toBe('Hafenlichter');
    const snapshot = schreiben.mock.calls.findIndex(([p]) => p.startsWith('.versionen/manuskript/flut.md/'));
    expect(snapshot).toBeGreaterThanOrEqual(0);
    expect(await fs.lesen(schreiben.mock.calls[snapshot]![0])).toBe(original);
    expect(schreiben.mock.calls.findIndex(([p]) => p === 'manuskript/flut.md')).toBeGreaterThan(snapshot);
    expect(schreiben.mock.calls.findIndex(([p]) => p === 'plan/kapitel/flut.md')).toBeGreaterThan(snapshot);
    const geladen = erstelleStore(); await geladen.getState().projektLaden(fs);
    expect(geladen.getState().daten!.kapitel.flut!.titel).toBe('Hafenlichter');
    expect(geladen.getState().daten!.plaene.flut!.titel).toBe('Hafenlichter');
    const text = store.getState().daten!.kapitel.flut!.text + '\n\nHafenlichter';
    await store.getState().speichereKapitel({...store.getState().daten!.kapitel.flut!,text});
    await store.getState().suche.undo();
    expect(store.getState().daten!.kapitel.flut!.titel).toBe(titel);
    expect(store.getState().daten!.plaene.flut!.titel).toBe(titel);
    expect(store.getState().daten!.kapitel.flut!.text).toBe(text);
    await geladen.getState().projektLaden(fs);
    expect(geladen.getState().daten!.kapitel.flut!.titel).toBe(titel);
    expect(geladen.getState().daten!.plaene.flut!.titel).toBe(titel);
    expect(geladen.getState().daten!.kapitel.flut!.text).toBe(text);
  });
  it('schreibt beim Umbenennen eines nur geplanten leeren Kapitels keine Manuskriptdatei', async () => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    const d = store.getState().daten!;
    await store.getState().speichereKapitel({...d.kapitel.flut!,text:''});
    await store.getState().speicherePlan({...d.plaene.flut!,status:'geplant'});
    const treffer = sucheProjekt(store.getState().daten!, d.plaene.flut!.titel).find(t => t.feld.pfad.join('/') === 'plaene/flut/titel')!;
    const schreiben = vi.spyOn(fs, 'schreiben');
    await store.getState().suche.ersetzen(treffer.feld.text, 'Hafenlichter', {}, {einzeln:treffer});
    expect(store.getState().daten!.plaene.flut!.titel).toBe('Hafenlichter');
    expect(schreiben.mock.calls.some(([p]) => p === 'manuskript/flut.md' || p.startsWith('.versionen/manuskript/flut.md/'))).toBe(false);
  });
  it('lässt bei fehlgeschlagenem Titel-Schnappschuss Plan und Manuskript unverändert', async () => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    const d = store.getState().daten!;
    const plan = await fs.lesen('plan/kapitel/flut.md'); const kapitel = await fs.lesen('manuskript/flut.md');
    const treffer = sucheProjekt(d, d.plaene.flut!.titel).find(t => t.feld.pfad.join('/') === 'plaene/flut/titel')!;
    const original = fs.schreiben.bind(fs);
    vi.spyOn(fs, 'schreiben').mockImplementation((p,t) => p.startsWith('.versionen/manuskript/flut.md/') ? Promise.reject(new Error('voll')) : original(p,t));
    const r = await store.getState().suche.ersetzen(treffer.feld.text, 'Hafenlichter', {}, {einzeln:treffer});
    expect(r.anzahl).toBe(0);
    expect(r.fehler[0]).toContain(d.kapitel.flut!.titel);
    expect(store.getState().daten!.plaene.flut).toEqual(d.plaene.flut);
    expect(store.getState().daten!.kapitel.flut).toEqual(d.kapitel.flut);
    expect(await fs.lesen('plan/kapitel/flut.md')).toBe(plan);
    expect(await fs.lesen('manuskript/flut.md')).toBe(kapitel);
  });
  it('verweigert gemeinsames Titel-Undo nach einer späteren Manuskript-Titeländerung', async () => {
    const store = erstelleStore(); await store.getState().projektLaden(demoFs());
    const d = store.getState().daten!;
    const treffer = sucheProjekt(d, d.plaene.flut!.titel).find(t => t.feld.pfad.join('/') === 'plaene/flut/titel')!;
    await store.getState().suche.ersetzen(treffer.feld.text, 'Hafenlichter', {}, {einzeln:treffer});
    await store.getState().speichereKapitel({...store.getState().daten!.kapitel.flut!,titel:'Spätere Änderung'});
    await expect(store.getState().suche.undo()).rejects.toThrow('inzwischen bearbeitet');
    expect(store.getState().daten!.plaene.flut!.titel).toBe('Hafenlichter');
    expect(store.getState().daten!.kapitel.flut!.titel).toBe('Spätere Änderung');
  });
  it('führt auch ohne bisherigen Tageseintrag nur stand in statistik.json nach', async () => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    await store.getState().speichereStatistik({version:1,ziel:{tagWoerter:0},tage:{}});
    const backend = erstelleDemoBackend();
    const senden = vi.spyOn(backend.ki,'senden');
    const tokens = vi.spyOn(backend.ki,'tokenZaehlen');
    store.setState({backend});
    await store.getState().suche.ersetzen('Volvo','ein altes Auto',{}, {kapitel:'flut'});
    await store.getState().statistik.sichern();
    const tag = tagSchluessel(new Date());
    const statistik = JSON.parse((await fs.lesen('statistik.json'))!);
    const d = store.getState().daten!;
    expect(statistik.tage[tag]).toEqual({geschrieben:0,stand:d.projekt.kapitel.reduce((n,id) => n + wortzahl(d.kapitel[id]!.text),0)});
    expect(senden).not.toHaveBeenCalled();
    expect(tokens).not.toHaveBeenCalled();
  });
  it('sichert beim Projektlauf alle betroffenen Kapitel vor ihrem Schreiben und erhält deren Originale', async () => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    const treffer = sucheProjekt(store.getState().daten!,'Bleistift').filter(t => t.feld.bereich === 'manuskript');
    const ids = [...new Set(treffer.map(t => t.feld.kapitel!))];
    expect(ids.length).toBeGreaterThan(1);
    const originale = new Map(await Promise.all(ids.map(async id => [id, await fs.lesen(`manuskript/${id}.md`)] as const)));
    const schreiben = vi.spyOn(fs,'schreiben');
    await store.getState().suche.ersetzen('Bleistift','Werkzeug',{},{});
    for (const id of ids) {
      const snapshot = schreiben.mock.calls.findIndex(([p]) => p.startsWith(`.versionen/manuskript/${id}.md/`));
      const kapitel = schreiben.mock.calls.findIndex(([p]) => p === `manuskript/${id}.md`);
      expect(snapshot).toBeGreaterThanOrEqual(0);
      expect(kapitel).toBeGreaterThan(snapshot);
      expect(await fs.lesen(schreiben.mock.calls[snapshot]![0])).toBe(originale.get(id));
    }
    expect(schreiben.mock.calls.filter(([p]) => p.startsWith('manuskript/')).every(([p]) => ids.some(id => p === `manuskript/${id}.md`))).toBe(true);
  });
  it('überschreibt beim Undo keine während eines vorherigen Schreibens bearbeiteten Felder', async () => {
    const store = erstelleStore(); await store.getState().projektLaden(demoFs());
    await store.getState().speichereFigur({...store.getState().daten!.figuren.lotte!,notizen:'Suchprobe'});
    await store.getState().speichereOrt({...store.getState().daten!.orte.lindenhof!,notizen:'Suchprobe'});
    await store.getState().suche.ersetzen('Suchprobe','Neu',{},{});
    const speichern = store.getState().speichereFigur;
    store.setState({speichereFigur: async figur => {
      await speichern(figur);
      await store.getState().speichereOrt({...store.getState().daten!.orte.lindenhof!,notizen:'Spätere Änderung'});
    }});
    await expect(store.getState().suche.undo()).rejects.toThrow('inzwischen bearbeitet');
    expect(store.getState().daten!.orte.lindenhof!.notizen).toBe('Spätere Änderung');
  });
  it('beschränkt bestätigte Treffer und verweigert Ersetzen nach Änderungen während der Rückfrage', async () => {
    const store = erstelleStore(); await store.getState().projektLaden(demoFs());
    const d = store.getState().daten!;
    await store.getState().speichereFigur({...d.figuren.lotte!,notizen:'Suchprobe'});
    const erwartet = sucheProjekt(store.getState().daten!,'Suchprobe');
    await store.getState().speichereOrt({...d.orte.lindenhof!,notizen:'Suchprobe'});
    await store.getState().suche.ersetzen('Suchprobe','Neu',{}, {erwartet});
    expect(store.getState().daten!.orte.lindenhof!.notizen).toBe('Suchprobe');
    const liste = sucheProjekt(store.getState().daten!,'Neu');
    await store.getState().speichereFigur({...store.getState().daten!.figuren.lotte!,notizen:'Neu geändert'});
    await expect(store.getState().suche.ersetzen('Neu','Alt',{}, {erwartet:liste})).rejects.toThrow('erneut suchen');
    await expect(store.getState().suche.undo()).rejects.toThrow('inzwischen bearbeitet');
    expect(store.getState().daten!.figuren.lotte!.notizen).toBe('Neu geändert');
  });
  it('erzwingt bei jedem Lauf einen neuen Schnappschuss und sucht Anker neu, statt sie umzudeuten', async () => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    const notiz = store.getState().daten!.anmerkungen.find(a => a.id === 'bleistift-motiv')!;
    await store.getState().suche.ersetzen('Bleistifte','Werkzeug',{}, {kapitel:'flut'});
    expect(store.getState().daten!.anmerkungen.find(a => a.id === notiz.id)!.anker).toEqual(notiz.anker);
    expect(ankerFinden(klartext(store.getState().daten!.kapitel.flut!.text),notiz.anker)).toBeNull();
    const n = (await fs.auflisten('.versionen/manuskript/flut.md')).length;
    await store.getState().suche.ersetzen('Werkzeug','Bleistifte',{}, {kapitel:'flut'});
    expect((await fs.auflisten('.versionen/manuskript/flut.md')).length).toBe(n+1);
  });
  it('sichert jedes betroffene Kapitel vorher, schreibt unbetroffene nicht und zählt nur stand', async () => {
    const fs = demoFs(); const store = erstelleStore();
    await store.getState().projektLaden(fs);
    const tag = tagSchluessel(new Date());
    await store.getState().speichereStatistik({version: 1, ziel: {tagWoerter: 0}, tage: {[tag]: {geschrieben: 7, stand: 0}}});
    const alt = await fs.lesen('manuskript/flut.md');
    const schreiben = vi.spyOn(fs, 'schreiben');
    await store.getState().suche.ersetzen('Volvo', '"ein altes Auto"', {}, {kapitel: 'flut'});
    const versionen = await fs.auflisten('.versionen/manuskript/flut.md');
    expect(versionen.length).toBeGreaterThan(0);
    expect(await fs.lesen(versionen[0]!)).toBe(alt);
    expect(schreiben.mock.calls.some(([p]) => p === 'manuskript/lotte.md')).toBe(false);
    expect(store.getState().daten!.kapitel.flut!.text).toContain('"ein altes Auto"');
    await store.getState().statistik.sichern();
    expect(store.getState().daten!.statistik!.tage[tag]!.geschrieben).toBe(7);
    expect(store.getState().daten!.statistik!.tage[tag]!.stand).toBeGreaterThan(0);
  });
  it('ändert ein Kapitel bei fehlgeschlagenem Schnappschuss nicht und nennt es', async () => {
    const fs = demoFs(); const store = erstelleStore(); await store.getState().projektLaden(fs);
    const alt = store.getState().daten!.kapitel.flut!;
    const original = fs.schreiben.bind(fs);
    vi.spyOn(fs, 'schreiben').mockImplementation((p, t) => p.startsWith('.versionen/manuskript/flut.md/') ? Promise.reject(new Error('voll')) : original(p,t));
    const r = await store.getState().suche.ersetzen('Volvo', 'Auto', {}, {kapitel: 'flut'});
    expect(r.fehler[0]).toContain('Flut');
    expect(store.getState().daten!.kapitel.flut).toBe(alt);
  });
  it('ersetzt Plan und private Notizen gemeinsam; Undo erhält spätere Änderungen anderer Felder und wird bei Projektwechsel gelöscht', async () => {
    const store = erstelleStore(); const fs = demoFs(); await store.getState().projektLaden(fs);
    const d = store.getState().daten!;
    await store.getState().speichereFigur({...d.figuren.lotte!, notizen: 'Suchprobe privat', plan: {...d.figuren.lotte!.plan, Eigenes: 'Suchprobe Plan'}});
    await store.getState().speichereOrt({...d.orte.lindenhof!, notizen: 'Suchprobe Ort'});
    await store.getState().suche.ersetzen('Suchprobe', 'Neu', {}, {});
    expect(sucheProjekt(store.getState().daten!, 'Suchprobe')).toHaveLength(0);
    await store.getState().speichereFigur({...store.getState().daten!.figuren.lotte!, kurz: 'Spätere Änderung'});
    await store.getState().suche.undo();
    expect(sucheProjekt(store.getState().daten!, 'Suchprobe')).toHaveLength(3);
    expect(store.getState().daten!.figuren.lotte!.kurz).toBe('Spätere Änderung');
    expect(await fs.lesen('figuren/lotte.md')).toContain('Suchprobe privat');
    await store.getState().suche.ersetzen('Suchprobe', 'Neu', {}, {});
    await store.getState().projektLaden(demoFs());
    expect(store.getState().suche.kannUndo).toBe(false);
  });
});
